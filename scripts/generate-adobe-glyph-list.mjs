// Regenerate from Adobe Glyph List 2.0:
// curl -fsSLO https://raw.githubusercontent.com/adobe-type-tools/agl-aglfn/master/glyphlist.txt
// node scripts/generate-adobe-glyph-list.mjs glyphlist.txt
import { readFile, writeFile } from "node:fs/promises";

const source = await readFile(process.argv[2], "utf8");
const entries = source.split(/\r?\n/).filter((line) => line && !line.startsWith("#"));
if (
  entries.length !== 4281 ||
  entries.some((entry) => !/^[A-Za-z0-9]+;[\dA-F]{4}(?: [\dA-F]{4})*$/.test(entry))
) {
  throw new Error("Expected the 4,281 entries of Adobe Glyph List 2.0");
}
const lines = [];
for (let index = 0; index < entries.length; index += 10) {
  lines.push(
    entries
      .slice(index, index + 10)
      .map((entry) => entry.replaceAll(" ", ","))
      .join(" "),
  );
}
const license = source
  .split("# -----------------------------------------------------------")[1]
  .split("\n")
  .map((line) => line.replace(/^# ?/, ""))
  .join("\n")
  .trim();
await writeFile(
  new URL("../src/content/adobe-glyph-list.ts", import.meta.url),
  `/*!
${license}
*/
// Adobe Glyph List 2.0: https://github.com/adobe-type-tools/agl-aglfn
// Generated by scripts/generate-adobe-glyph-list.mjs; ten entries per line.
// Entries are name;hex[,hex...], separated by whitespace.
const data = \`
${lines.join("\n")}
\`;

export const adobeGlyphList: ReadonlyMap<string, string> = new Map(
  data
    .trim()
    .split(/\\s+/)
    .map((entry) => {
      const separator = entry.indexOf(";");
      const points = entry
        .slice(separator + 1)
        .split(",")
        .map((point) => Number.parseInt(point, 16));
      return [entry.slice(0, separator), String.fromCodePoint(...points)];
    }),
);
`,
);
